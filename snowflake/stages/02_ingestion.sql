USE ROLE SYSADMIN;
USE WAREHOUSE COMPUTE_WH;
USE DATABASE RETAIL_DEV;
USE SCHEMA RAW;

--VERIFY
SELECT 
CURRENT_ROLE(),
CURRENT_WAREHOUSE(),
CURRENT_DATABASE(),
CURRENT_SCHEMA();

-- Create an Internal Stage
CREATE STAGE IF NOT EXISTS RETAIL_DEV.RAW.RETAIL_SOURCE_STAGE
    COMMENT='Internal Stage for retail source CSV files';
-- verify the stage
SHOW STAGES IN SCHEMA RETAIL_DEV.RAW;

DESC STAGE RETAIL_DEV.RAW.RETAIL_SOURCE_STAGE;

--list of files in satge
LIST @RETAIL_DEV.RAW.RETAIL_SOURCE_STAGE;

--create a file format
CREATE FILE FORMAT IF NOT EXISTS RETAIL_DEV.RAW.RETAIL_CSV_FORMAT
TYPE = CSV
FIELD_DELIMITER = ','
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
NULL_IF = ('NULL', 'null', '')
EMPTY_FIELD_AS_NULL = TRUE
TRIM_SPACE = TRUE
COMMENT = 'CSV format for retail source datasets';

--verify the file format
SHOW FILE FORMATS IN SCHEMA RETAIL_DEV.RAW;
 --description about file formats
 DESC FILE FORMAT RETAIL_DEV.RAW.RETAIL_CSV_FORMAT;

-- Preview a staged CSV before loading
SELECT
    $1 AS CUSTOMER_ID,
    $2 AS NAME,
    $3 AS CITY,
    $4 AS EMAIL,
    $5 AS STATUS
FROM @RETAIL_DEV.RAW.RETAIL_SOURCE_STAGE/customers.csv
(FILE_FORMAT => 'RETAIL_DEV.RAW.RETAIL_CSV_FORMAT')
LIMIT 10;

-- CREATE TABLE for RAW_CUSTOMERS
CREATE TABLE IF NOT EXISTS RETAIL_DEV.RAW.RAW_CUSTOMERS(
    CUSTOMER_ID VARCHAR(50),
    NAME VARCHAR(50),
    CITY VARCHAR(50),
    EMAIL VARCHAR(50),
    STATUS VARCHAR(50)
)
COMMENT = 'Raw customer data loaded from customer.csv';

--verify the table
DESC TABLE RETAIL_DEV.RAW.RAW_CUSTOMERS;

--correct the size of varchar
ALTER TABLE RETAIL_DEV.RAW.RAW_CUSTOMERS
    ALTER COLUMN NAME SET DATA TYPE VARCHAR(100);

ALTER TABLE RETAIL_DEV.RAW.RAW_CUSTOMERS
    ALTER COLUMN CITY SET DATA TYPE VARCHAR(100);

ALTER TABLE RETAIL_DEV.RAW.RAW_CUSTOMERS
    ALTER COLUMN EMAIL SET DATA TYPE VARCHAR(255);

-- DESC THE TABLE
DESC TABLE RETAIL_DEV.RAW.RAW_CUSTOMERS;

-- COPY DATA STAGE TO TABLE
COPY INTO RETAIL_DEV.RAW.RAW_CUSTOMERS
FROM @RETAIL_DEV.RAW.RETAIL_SOURCE_STAGE/customers.csv
FILE_FORMAT = ( FORMAT_NAME = 'RETAIL_DEV.RAW.RETAIL_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

--verify the loaded records
SELECT COUNT(*) AS TOTAL_CUSTOMERS 
FROM RETAIL_DEV.RAW.RAW_CUSTOMERS;

SELECT *
FROM RETAIL_DEV.RAW.RAW_CUSTOMERS
LIMIT 10;

-- Verify the load history
SELECT
    FILE_NAME,
    STATUS,
    ROW_COUNT,
    ROW_PARSED,
    LAST_LOAD_TIME
FROM TABLE(
    RETAIL_DEV.INFORMATION_SCHEMA.COPY_HISTORY(
        TABLE_NAME => 'RAW_CUSTOMERS',
        START_TIME => DATEADD('HOUR', -1, CURRENT_TIMESTAMP())
    )
);

-- create remaining raw tables
-- 1. PRODUCTS
CREATE TABLE IF NOT EXISTS RETAIL_DEV.RAW.RAW_PRODUCTS (
    PRODUCT_ID VARCHAR(50),
    CATEGORY VARCHAR(100),
    PRICE NUMBER(12,2),
    COST NUMBER(12,2)
);

-- 2. ORDERS
CREATE TABLE IF NOT EXISTS RETAIL_DEV.RAW.RAW_ORDERS (
    ORDER_ID VARCHAR(50),
    CUSTOMER_ID VARCHAR(50),
    ORDER_DATE DATE,
    STATUS VARCHAR(50)
);

-- 3. ORDER ITEMS
CREATE TABLE IF NOT EXISTS RETAIL_DEV.RAW.RAW_ORDER_ITEMS (
    ORDER_ID VARCHAR(50),
    PRODUCT_ID VARCHAR(50),
    QUANTITY NUMBER(10,0),
    UNIT_PRICE NUMBER(12,2)
);

-- 4. PAYMENTS
CREATE TABLE IF NOT EXISTS RETAIL_DEV.RAW.RAW_PAYMENTS (
    PAYMENT_ID VARCHAR(50),
    ORDER_ID VARCHAR(50),
    PAYMENT_STATUS VARCHAR(50),
    AMOUNT NUMBER(12,2)
);

-- 5. INVENTORY
CREATE TABLE IF NOT EXISTS RETAIL_DEV.RAW.RAW_INVENTORY (
    PRODUCT_ID VARCHAR(50),
    WAREHOUSE_ID VARCHAR(50),
    STOCK_QUANTITY NUMBER(10,0)
);
-- verify
SHOW TABLES IN SCHEMA RETAIL_DEV.RAW;

