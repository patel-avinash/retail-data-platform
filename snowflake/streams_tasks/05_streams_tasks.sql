-- Currently, our Task only handles new INSERT records. We will replace its SQL logic with a MERGE operation.

CREATE OR REPLACE TASK RETAIL_DEV.RAW.PROCESS_CUSTOMER_STREAM_TASK
WAREHOUSE = COMPUTE_WH
SCHEDULE = '1 MINUTE'
WHEN SYSTEM$STREAM_HAS_DATA(
    'RETAIL_DEV.RAW.CUSTOMERS_STREAM'
)
AS
MERGE INTO RETAIL_DEV.STAGING.CUSTOMERS_STREAM_TARGET T
USING (
    SELECT
        CUSTOMER_ID,
        NAME,
        CITY,
        EMAIL,
        STATUS,
        INGESTED_AT
    FROM RETAIL_DEV.RAW.CUSTOMERS_STREAM
    WHERE METADATA$ACTION = 'INSERT'
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY CUSTOMER_ID
        ORDER BY INGESTED_AT DESC
    ) = 1
) S
ON T.CUSTOMER_ID = S.CUSTOMER_ID

WHEN MATCHED THEN UPDATE SET
    T.NAME = S.NAME,
    T.CITY = S.CITY,
    T.EMAIL = S.EMAIL,
    T.STATUS = S.STATUS,
    T.INGESTED_AT = S.INGESTED_AT

WHEN NOT MATCHED THEN INSERT (
    CUSTOMER_ID,
    NAME,
    CITY,
    EMAIL,
    STATUS,
    INGESTED_AT
)
VALUES (
    S.CUSTOMER_ID,
    S.NAME,
    S.CITY,
    S.EMAIL,
    S.STATUS,
    S.INGESTED_AT
);

-- resumme the updated task
ALTER TASK RETAIL_DEV.RAW.PROCESS_CUSTOMER_STREAM_TASK RESUME;
ALTER TASK RETAIL_DEV.RAW.PROCESS_CUSTOMER_STREAM_TASK SUSPEND;

