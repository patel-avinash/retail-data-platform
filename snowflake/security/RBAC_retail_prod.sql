USE ROLE SYSADMIN;
SELECT CURRENT_ROLE();

-- Grant production database access

-- DATA_ENGINEER
GRANT USAGE ON DATABASE RETAIL_PROD
TO ROLE DATA_ENGINEER;

-- DBT_DEVELOPER
GRANT USAGE ON DATABASE RETAIL_PROD
TO ROLE DBT_DEVELOPER;

-- BI_ANALYST
GRANT USAGE ON DATABASE RETAIL_PROD
TO ROLE BI_ANALYST;

-- Grant schema-level privileges

-- DATA_ENGINEER: RAW only
GRANT USAGE ON SCHEMA RETAIL_PROD.RAW
TO ROLE DATA_ENGINEER;

-- DBT_DEVELOPER: All three schemas
GRANT USAGE ON SCHEMA RETAIL_PROD.RAW
TO ROLE DBT_DEVELOPER;

GRANT USAGE ON SCHEMA RETAIL_PROD.STAGING
TO ROLE DBT_DEVELOPER;

GRANT USAGE ON SCHEMA RETAIL_PROD.MART
TO ROLE DBT_DEVELOPER;

-- BI_ANALYST: MART only
GRANT USAGE ON SCHEMA RETAIL_PROD.MART
TO ROLE BI_ANALYST;

-- Grant object-level privileges
-- DATA_ENGINEER — RAW operations

GRANT CREATE TABLE
ON SCHEMA RETAIL_PROD.RAW
TO ROLE DATA_ENGINEER;

GRANT CREATE STAGE
ON SCHEMA RETAIL_PROD.RAW
TO ROLE DATA_ENGINEER;

GRANT CREATE FILE FORMAT
ON SCHEMA RETAIL_PROD.RAW
TO ROLE DATA_ENGINEER;

-- DBT_DEVELOPER — Transformation operations

-- Read RAW tables
GRANT SELECT ON ALL TABLES
IN SCHEMA RETAIL_PROD.RAW
TO ROLE DBT_DEVELOPER;

GRANT SELECT ON FUTURE TABLES
IN SCHEMA RETAIL_PROD.RAW
TO ROLE DBT_DEVELOPER;

-- Create STAGING and MART models
GRANT CREATE TABLE, CREATE VIEW
ON SCHEMA RETAIL_PROD.STAGING
TO ROLE DBT_DEVELOPER;

GRANT CREATE TABLE, CREATE VIEW
ON SCHEMA RETAIL_PROD.MART
TO ROLE DBT_DEVELOPER;

-- BI_ANALYST — Read-only analytics

-- Read existing MART tables and views
GRANT SELECT ON ALL TABLES
IN SCHEMA RETAIL_PROD.MART
TO ROLE BI_ANALYST;

GRANT SELECT ON ALL VIEWS
IN SCHEMA RETAIL_PROD.MART
TO ROLE BI_ANALYST;

-- Read future MART tables and views
GRANT SELECT ON FUTURE TABLES
IN SCHEMA RETAIL_PROD.MART
TO ROLE BI_ANALYST;

GRANT SELECT ON FUTURE VIEWS
IN SCHEMA RETAIL_PROD.MART
TO ROLE BI_ANALYST;

